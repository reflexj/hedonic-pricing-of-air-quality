"""
HE3027 Group Project: figure and numbers on how PM10 changed over the sample period, for the data section of the
report.

Writes figures/report_pm10_trend.png and report_pm10_figure.md.

Run from the Code folder:
    python report_pm10_figure.py

Needs: pandas, numpy, matplotlib
Data:  data/land_registry_pollution.dta
"""

import matplotlib.pyplot as plt
import numpy as np

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "models"))   # the model scripts live in models/

from model_v1 import CODE_DIR, load_data
from model_v1_pm10_smoothing import add_smoothed_pm10

FIG_DIR = CODE_DIR / "figures"
FIG_FILE = FIG_DIR / "report_pm10_trend.png"
MD_FILE = CODE_DIR / "report_pm10_figure.md"
FIRST, LAST = 2007, 2014        # v3 sample (the 3-year average needs 2005 and 2006)


def main():
    df, full, _ = load_data()
    df, panel = add_smoothed_pm10(df, full)          # panel: years in rows, LSOAs in columns (yearly PM10)
    ma3 = panel.rolling(3, min_periods=3).mean()

    yearly = full.groupby("year")["pm10"].mean()      # mean over sales, as in data_exploration.md
    q10, q90 = panel.quantile(0.1, axis=1), panel.quantile(0.9, axis=1)
    ma3_mean = df[df["year"].between(FIRST, LAST)].groupby("year")["pm10_ma3"].mean()
    sites = full.groupby("year")["pm10"].nunique()

    # change in the 3-year average per LSOA over the v3 period
    both = ma3.loc[[FIRST, LAST]].T.dropna()
    change = both[LAST] - both[FIRST]
    yr_change = (panel.loc[LAST] - panel.loc[FIRST]).dropna()

    # v3 sample (sales with a 3-year average) and the PM10 variation the model uses
    v3 = df.dropna(subset=["pm10_ma3"])
    within = v3["pm10_ma3"] - v3.groupby("lsoacode")["pm10_ma3"].transform("mean")
    left = within - within.groupby(v3["yearquarter"]).transform("mean")

    # ---- figure ----
    FIG_DIR.mkdir(exist_ok=True)
    plt.rcParams.update({"font.size": 10, "axes.edgecolor": "#8a8984", "axes.labelcolor": "#52514e",
                         "xtick.color": "#52514e", "ytick.color": "#52514e"})
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 4.2), gridspec_kw={"width_ratios": [1.45, 1]})

    a1.axvspan(FIRST - 0.5, LAST + 0.5, color="#f1f0ec", zorder=0)
    a1.text(FIRST - 0.35, 36.6, "v3 sample", fontsize=8, color="#52514e", va="top")
    a1.fill_between(q10.index, q10, q90, color="#2a78d6", alpha=0.15, linewidth=0,
                    label="10th-90th percentile across LSOAs")
    a1.plot(yearly.index, yearly, "o-", color="#2a78d6", markersize=4, label="Yearly PM10, mean over sales")
    a1.plot(ma3_mean.index, ma3_mean, "s-", color="#eb6834", markersize=4,
            label="3-year average (v3 measure), mean over sales")
    a1.set_xticks(range(2005, 2016, 2))
    a1.set_ylim(14, 37)
    a1.set_ylabel("PM10 (µg/m³)")
    a1.set_title("(a) PM10 at the nearest monitoring site", loc="left", fontsize=10, color="#0b0b0b")
    a1.grid(axis="y", color="#e4e3df", linewidth=0.8, zorder=0)
    a1.spines[["top", "right"]].set_visible(False)
    a1.legend(frameon=False, fontsize=8, loc="lower left")

    a2.hist(left.clip(-6, 6), bins=np.arange(-6, 6.25, 0.25), weights=np.full(len(left), 100 / len(left)),
            color="#2a78d6", edgecolor="white", linewidth=0.3)
    a2.axvline(0, color="#52514e", linewidth=0.8)
    a2.text(0.97, 0.95, f"std. dev. {left.std():.2f} µg/m³\n{(left.abs() <= 1).mean() * 100:.0f}% within ±1",
            transform=a2.transAxes, ha="right", va="top", fontsize=8, color="#0b0b0b")
    a2.set_xlabel("3-year PM10 minus LSOA and quarter means (µg/m³)")
    a2.set_ylabel("% of sales")
    a2.set_title("(b) PM10 variation used by the v3 model", loc="left", fontsize=10, color="#0b0b0b")
    a2.spines[["top", "right"]].set_visible(False)

    fig.text(0.01, 0.01, "Source: Land Registry sales in London with PM10 at the nearest monitoring site, prices "
             "trimmed at 1%/99%. 2015: January-July. (b): v3 sample, 2007-2014; values beyond ±6 shown at ±6.",
             fontsize=7.5, color="#52514e")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(FIG_FILE, dpi=220)

    # ---- numbers for the text ----
    rows = "\n".join(f"| {y} | {yearly[y]:.2f} | {q10[y]:.1f} - {q90[y]:.1f} | "
                     + (f"{ma3_mean[y]:.2f}" if y in ma3_mean.index else "") + f" | {sites[y]} |"
                     for y in yearly.index)
    md = f"""# PM10 Over Time (Report Figure)

Generated by `report_pm10_figure.py`. Figure: `figures/report_pm10_trend.png`.

| Year | Yearly PM10, mean over sales | 10th-90th percentile across LSOAs | 3-year average, mean over v3 sales | Monitoring sites in use |
|---|---|---|---|---|
{rows}

- Yearly PM10 {FIRST} to {LAST}: {yearly[FIRST]:.2f} to {yearly[LAST]:.2f} µg/m³; 2005 to 2015: {yearly[2005]:.2f} to {yearly[2015]:.2f}.
- 3-year average, mean over v3 sales: {ma3_mean[FIRST]:.2f} ({FIRST}) to {ma3_mean[LAST]:.2f} ({LAST}); peak {ma3_mean.max():.2f} in {ma3_mean.idxmax()}.
- Change in the 3-year average per LSOA, {FIRST} to {LAST} ({len(change):,} LSOAs): mean {change.mean():+.2f}, std. dev.
  {change.std():.2f}, 10th-90th percentile {change.quantile(0.1):+.2f} to {change.quantile(0.9):+.2f}; fell in
  {(change < 0).mean() * 100:.0f}% of LSOAs.
- Change in yearly PM10 per LSOA, {FIRST} to {LAST} ({len(yr_change):,} LSOAs): mean {yr_change.mean():+.2f},
  std. dev. {yr_change.std():.2f}.

## v3 sample

- Sales: {len(v3):,}; LSOAs: {v3['lsoacode'].nunique():,}; MSOAs: {v3['msoa11'].nunique():,}; boroughs:
  {v3['oslaua'].nunique()}; years {v3['year'].min()}-{v3['year'].max()}.
- Mean price £{v3['price'].mean():,.0f} (median £{v3['price'].median():,.0f}); flats {(v3['propertyty'] == 'F').mean() * 100:.1f}%.
- 3-year average PM10: mean {v3['pm10_ma3'].mean():.2f}, std. dev. {v3['pm10_ma3'].std():.2f}, range
  {v3['pm10_ma3'].min():.1f} to {v3['pm10_ma3'].max():.1f} µg/m³.
- Std. dev. left after removing LSOA means: {within.std():.2f}; after also removing year-quarter means:
  {left.std():.2f} ({(left.var() / v3['pm10_ma3'].var()) * 100:.1f}% of the total variance); within ±1 µg/m³:
  {(left.abs() <= 1).mean() * 100:.0f}% of sales; 5th-95th percentile {left.quantile(0.05):+.2f} to {left.quantile(0.95):+.2f}.
"""
    MD_FILE.write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
