"""
HE3027 Group Project: total cost of PM10 for London homes, using the v3 estimate.

Turns the v3 willingness to pay per home and per µg/m³ into a London-wide figure:

    total cost = WTP per home per µg/m³ × change in PM10 × number of dwellings
    annual cost = total cost × discount rate

for four benchmarks (1 µg/m³, the WHO 2005 and 2021 guidelines, the observed decline 2005-2015), with a 95%
confidence interval from the v3 standard error and a version that uses the four v3 group effects.

Writes total_cost_using_v3.md.

Run from the Code folder (after model_v3.py has been run once, so that the road and green caches exist):
    python total_cost_using_v3.py

Needs: the same packages and data as model_v3.py
"""

import numpy as np
import pandas as pd

from model_v1 import CODE_DIR, DATA_DIR, TRIM
from model_v1_income_small_area import lincom
from model_v2 import coef, with_pm
from model_v3 import GREEN_TERMS, MAIN, V3_CONTROLS, finish, fit, prepare

MD_FILE = CODE_DIR / "total_cost_using_v3.md"

# ---------------------------------------------------------------------------
# External inputs (sources in the markdown)
# ---------------------------------------------------------------------------
DWELLINGS = 3_318_000      # London dwelling stock, 31 March 2011 (DCLG dwelling stock estimates, Table 2)
CENSUS_FLAT_SHARE = 0.516  # London households in flats and other non-house accommodation, Census 2011
RATE = 0.035               # HM Treasury Green Book discount rate
WHO_2005 = 20.0            # WHO air quality guideline 2005, annual mean PM10 (µg/m³)
WHO_2021 = 15.0            # WHO air quality guideline 2021, annual mean PM10 (µg/m³)
Z = 1.96


def bn(x):
    return f"£{x / 1e9:,.1f}bn"


def mn(x):
    return f"£{x / 1e9:,.2f}bn" if x >= 1e9 else f"£{x / 1e6:,.0f}m"


def gbp(x):
    return f"£{x:,.0f}"


def main():
    df = prepare()
    d = finish(with_pm(df.dropna(subset=["green_500", "dist_major_m"]), "pm10_ma3"))    # v3 sample

    # v3 estimates (same models as model_v3.py)
    v3_avg = fit(d, ["pm10"] + V3_CONTROLS + GREEN_TERMS)     # average PM10 effect, no interactions
    v3 = fit(d, MAIN)                                         # main model with the two interactions
    b, s = coef(v3_avg, "pm10")
    price = d["price"].mean()
    pm_mean = d["pm10"].mean()
    wtp, wtp_lo, wtp_hi = -b * price, -(b + Z * s) * price, -(b - Z * s) * price
    flat_share = (d["house"] == 0).mean()

    # Observed decline in yearly PM10: mean over all sales per year, prices trimmed, 2005-2015
    # (same numbers as figures/pm10_over_time.png in data_exploration.py)
    raw = pd.read_stata(DATA_DIR / "land_registry_pollution.dta", columns=["price", "pm10", "year"],
                        convert_categoricals=False)
    lo_p, hi_p = raw["price"].quantile([TRIM, 1 - TRIM])
    by_year = raw[raw["price"].between(lo_p, hi_p)].groupby("year")["pm10"].mean()
    y0, y1 = int(by_year.index.min()), int(by_year.index.max())
    decline = by_year.loc[y0] - by_year.loc[y1]

    scen = [
        ("1 µg/m³ less PM10 everywhere", 1.0),
        (f"Down to the WHO 2005 guideline ({WHO_2005:.0f} µg/m³)", pm_mean - WHO_2005),
        (f"Down to the WHO 2021 guideline ({WHO_2021:.0f} µg/m³)", pm_mean - WHO_2021),
        (f"Observed decline {y0}-{y1} (a benefit, not a cost)", decline),
    ]
    rows, res = [], {}
    for lab, dpm in scen:
        lin = wtp * dpm
        exact = price * (np.exp(-b * dpm) - 1)
        tot = lin * DWELLINGS
        lo, hi = wtp_lo * dpm * DWELLINGS, wtp_hi * dpm * DWELLINGS
        res[lab] = (dpm, lin, exact, tot, lo, hi)
        rows.append(f"| {lab} | {dpm:.1f} | {gbp(lin)} | {gbp(exact)} | **{bn(tot)}** | {bn(lo)} to {bn(hi)} | "
                    f"{mn(tot * RATE)} | {gbp(lin * RATE)} |")

    # Group version: the four v3 group effects, weighted by their share of sales
    low = d["lowgreen"] == 1
    groups = [
        ("Flats, greener postcodes", {"pm10": 1}, (d["house"] == 0) & ~low),
        ("Flats, least green third", {"pm10": 1, "pm10_x_lowgreen": 1}, (d["house"] == 0) & low),
        ("Houses, greener postcodes", {"pm10": 1, "pm10_x_house": 1}, (d["house"] == 1) & ~low),
        ("Houses, least green third", {"pm10": 1, "pm10_x_house": 1, "pm10_x_lowgreen": 1},
         (d["house"] == 1) & low),
    ]
    g = []
    for lab, w, mask in groups:
        c, _ = lincom(v3, w)
        g.append((lab, c, -c * d.loc[mask, "price"].mean(), mask.mean()))
    wtp_g = sum(w_ * sh for _, _, w_, sh in g)
    g_rows = [f"| {lab} | {c * 100:+.2f}% | {gbp(w_)} | {sh * 100:.1f}% | {w_ * sh / wtp_g * 100:.0f}% |"
              for lab, c, w_, sh in g]

    one = res[scen[0][0]]
    who5 = res[scen[1][0]]
    md = f"""# Total Cost of PM10 for London Homes, Using Model v3

Generated by `total_cost_using_v3.py`. The estimates come from the v3 model (`model_v3.md`); the dwelling stock,
the WHO guidelines and the discount rate are external inputs (sources at the end).

## 1. Method

The v3 coefficient gives the willingness to pay (WTP) of a home buyer for 1 µg/m³ less PM10, as a share of the
price. Scaling it up to London:

- **Per home:** WTP = −β × mean price.
- **London:** total cost = WTP × ΔPM10 × number of dwellings.
- **Per year:** the price discount is the present value of all future pollution costs, so the annual cost is
  total cost × discount rate.

ΔPM10 needs a benchmark: the cost of pollution is always the cost *relative to* some cleaner level. We use four.
The linear formula is a first-order approximation; the exact log-model version is mean price ×
(exp(−β × ΔPM10) − 1), shown as a check.

## 2. Inputs

| Input | Value | Source |
|---|---|---|
| Average PM10 effect β (v3 without interactions) | {b * 100:+.3f}% per µg/m³ (s.e. {s * 100:.3f} pp) | `model_v3.md` |
| Mean sale price, v3 sample (2007-2014, trimmed, nominal) | {gbp(price)} | v3 sample |
| **WTP per home per µg/m³** | **{gbp(wtp)}** (95% CI {gbp(wtp_lo)} to {gbp(wtp_hi)}) | −β × mean price |
| Mean 3-year PM10, v3 sample | {pm_mean:.2f} µg/m³ | v3 sample |
| Observed decline in yearly PM10, {y0}-{y1} | {by_year.loc[y0]:.1f} to {by_year.loc[y1]:.1f} µg/m³ ({decline:.1f}) | All sales, prices trimmed, as in `figures/pm10_over_time.png` ({y1}: January-July) |
| London dwellings, 31 March 2011 | {DWELLINGS:,} | DCLG dwelling stock estimates |
| Discount rate | {RATE:.1%} | HM Treasury Green Book |

The v3 sample has {flat_share:.1%} flats; in the 2011 Census {CENSUS_FLAT_SHARE:.1%} of London households lived in
flats or other non-house accommodation. The sales are therefore close to the housing stock in this respect, which
supports scaling the per-home WTP up to all dwellings.

## 3. Total cost by benchmark

| Benchmark | ΔPM10 (µg/m³) | Per home (linear) | Per home (exact) | London total | 95% CI | Per year at {RATE:.1%} | Per home per year |
|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

95% CI from β ± 1.96 standard errors (MSOA-clustered). "Per year" = London total × {RATE:.1%}.

- **1 µg/m³:** London homes would be worth about **{bn(one[3])}** more for 1 µg/m³ less PM10 ({bn(one[4])} to
  {bn(one[5])}), about {mn(one[3] * RATE)} a year.
- **WHO 2005 guideline:** reducing PM10 from the sample mean of {pm_mean:.1f} to 20 µg/m³ is worth about
  **{bn(who5[3])}** ({mn(who5[3] * RATE)} a year, {gbp(who5[1] * RATE)} per home and year).
- The exact and linear versions differ by at most {(res[scen[2][0]][2] / res[scen[2][0]][1] - 1) * 100:.0f}%, so
  the linear formula is enough at these magnitudes.

## 4. Using the four group effects

The main v3 model gives different PM10 effects for flats and houses and for the least green third of postcodes.
Weighting the group WTPs by their share of sales gives a second estimate of the average WTP per home.

| Group | PM10 effect | WTP per µg/m³ | Share of sales | Share of total cost |
|---|---|---|---|---|
{chr(10).join(g_rows)}

- Weighted WTP per home: **{gbp(wtp_g)}** per µg/m³ (vs {gbp(wtp)} from the average effect), so
  **{bn(wtp_g * DWELLINGS)}** per µg/m³ for London (vs {bn(one[3])}). The two give a range rather than one number.
- The cost is concentrated in flats: flats in the least green third are {g[1][3] * 100:.1f}% of sales but bear
  {g[1][2] * g[1][3] / wtp_g * 100:.0f}% of the cost; houses in greener postcodes are {g[2][3] * 100:.1f}% of sales
  and bear {g[2][2] * g[2][3] / wtp_g * 100:.0f}%.

## 5. Caveats

- **Marginal WTP.** A hedonic coefficient measures WTP for small changes. 1 µg/m³ is within the variation used for
  the estimate; the gaps to the WHO guidelines ({pm_mean - WHO_2005:.1f} and {pm_mean - WHO_2021:.1f} µg/m³) go
  beyond it, so these rows are first-order approximations only.
- **Probably a lower bound.** PM10 comes from the nearest of about 60 to 74 monitoring sites; the remaining
  measurement error biases β towards zero.
- **Only what is capitalised.** The figure covers what buyers perceive and pay for in house prices, not the full
  social cost of pollution (for example health effects buyers do not perceive).
- **Renters.** About half of London households rent. Applying the WTP to all dwellings assumes the same
  capitalisation into rents.
- **Prices.** The mean is the mean transaction price of the v3 sample (2007-2014, nominal, top and bottom 1%
  trimmed), not the mean value of the dwelling stock.
- **Not causal.** As for the v3 coefficient itself.

## Sources

- DCLG (2011), *Dwelling Stock Estimates: 2011, England*, Table 2 (London: 3,318 thousand dwellings).
  [PDF](https://assets.publishing.service.gov.uk/media/5a78b2e5e5274a277e68ec53/2039750.pdf)
- GLA Intelligence (2013), *2011 Census: Housing characteristics* (London households by accommodation type).
  [PDF](https://data.london.gov.uk/download/20og1/377bcc89-fab4-4f88-a69f-10a2570cbde5/2011-census-housing-characteristics.pdf)
- WHO (2006), *Air Quality Guidelines: Global Update 2005* (PM10 annual mean 20 µg/m³).
- WHO (2021), *WHO Global Air Quality Guidelines* (PM10 annual mean 15 µg/m³).
  [Link](https://iris.who.int/handle/10665/345329)
- HM Treasury, *The Green Book* (discount rate 3.5%).
  [Link](https://www.gov.uk/government/publications/the-green-book-appraisal-and-evaluation-in-central-government)
"""
    MD_FILE.write_text(md, encoding="utf-8")
    print(f"Wrote {MD_FILE}")
    print(f"b={b:.5f} s={s:.5f} price={price:,.0f} pm_mean={pm_mean:.3f} wtp={wtp:,.0f} wtp_g={wtp_g:,.0f}")
    print(by_year.round(2).to_dict())


if __name__ == "__main__":
    main()
